import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MAX_BYTES = 5 * 1024 * 1024;
const CACHEABLE = /\.(?:html|css|js|mjs|json|webmanifest|webp|png|jpe?g|svg|ico|woff2?|ttf|mp3|ogg|wav)$/i;

export async function collectAssets(directory, prefix = '') {
  const assets = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = prefix + entry.name;
    if (entry.isDirectory()) assets.push(...await collectAssets(path.join(directory, entry.name), `${relative}/`));
    else if (entry.isFile() && entry.name !== 'sw.js' && CACHEABLE.test(entry.name)) {
      const bytes = await readFile(path.join(directory, entry.name));
      assets.push({ url: relative, size: bytes.length, integrity: 'sha256-' + createHash('sha256').update(bytes).digest('base64') });
    }
  }
  return assets.sort((a, b) => a.url.localeCompare(b.url, 'en'));
}

export function renderServiceWorker(assets) {
  const isPacked=asset=>/^assets\/v3(?:-b)?\//.test(asset.url)&&(asset.stage??3)>1&&!/^assets\/v3(?:-b)?\/(?:vegetable-cart|fruit-cart|chopping-board|fruit-press)-l1\.(?:webp|svg)$/.test(asset.url);
  const packs=assets.filter(isPacked);
  const allAssets=assets;
  assets=assets.filter(asset=>!packs.includes(asset));
  const index = assets.find(asset => asset.url === 'index.html');
  if (!index) throw new Error('PWA build requires dist/index.html. Run vite build first.');
  const total = assets.reduce((sum, asset) => sum + asset.size, 0);
  if (total > MAX_BYTES) throw new Error(`PWA precache exceeds 5 MiB: ${total} bytes.`);
  if(allAssets.reduce((sum,a)=>sum+a.size,0)>16*1024*1024)throw new Error('Complete offline release exceeds 16 MiB.');
  const version = createHash('sha256').update(JSON.stringify(allAssets)).update(renderServiceWorker.toString()).digest('hex').slice(0, 20);
  return `/* Generated by scripts/build-sw.mjs. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const ASSETS = ${JSON.stringify(assets)};
const PACKS = ${JSON.stringify(packs)};
const SCOPE = self.registration.scope;
const PREFIX = 'goose-lane::' + SCOPE + '::';
const CACHE = PREFIX + VERSION;
const PACK_CACHE = CACHE + '::themes';
// Every stored file is pinned by this release's URL and SHA-256. A preload
// request and a later CORS module/image request can carry different Origin
// headers; Vary: Origin must not hide the verified same static file offline.
const ASSET_ROOT = new URL('assets/', SCOPE).href;
const URLS = new Set(ASSETS.map(asset => new URL(asset.url, SCOPE).href));
const INDEX = new URL('index.html', SCOPE).href;
const INDEX_INTEGRITY = ${JSON.stringify(index.integrity)};
const RECOVERY_HTML = ${JSON.stringify(`<!doctype html><html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>鹅巷食光 · 恢复加载</title><style>body{font:16px/1.8 system-ui,sans-serif;color:#594a32;background:#fff7e5;margin:0;padding:48px 24px}main{max-width:420px;margin:auto}a,button{display:block;box-sizing:border-box;width:100%;margin:16px 0;padding:12px;border:1px solid #819b70;border-radius:12px;background:#e1efd7;color:#365c40;font:inherit;text-align:center;text-decoration:none}</style></head><body><main><h1>暂时无法加载游戏</h1><p>离线页面已经缺失，当前也未能连上游戏服务器。请联网后重试。也可直接打开 B 组试玩。</p><button onclick="location.reload()">重新加载</button><a href="https://emtismine520.github.io/goose-lane-art-preview/recover.html">直接打开 B 组试玩</a></main></body></html>`)};

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE);
      await cache.addAll(ASSETS.map(asset => new Request(new URL(asset.url, SCOPE), { cache: 'reload', integrity: asset.integrity })));
    } catch (error) {
      await caches.delete(CACHE);
      throw error;
    }
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') event.waitUntil(self.skipWaiting());
  if(event.data?.type==='CACHE_THEMES')event.waitUntil((async()=>{
    const stage=Number(event.data.stage);if(!Number.isInteger(stage)||stage<1||stage>8)return;
    const cache=await caches.open(PACK_CACHE);
    for(const asset of PACKS.filter(a=>(a.stage||3)<=stage)){
      const url=new URL(asset.url,SCOPE).href;if(await cache.match(url,{ignoreVary:true}))continue;
      const response=await fetch(new Request(url,{integrity:asset.integrity}));if(!response.ok)throw new Error('Theme download failed');await cache.put(url,response);
    }
    const missing=await Promise.all(PACKS.map(async asset=>(await cache.match(new URL(asset.url,SCOPE).href,{ignoreVary:true}))?9:(asset.stage||3)));
    const cachedStage=Math.max(1,Math.min(9,...missing)-1);
    event.source?.postMessage({type:'THEMES_CACHED',stage:cachedStage});
  })().catch(()=>{event.source?.postMessage({type:'THEMES_CACHE_FAILED'});}));
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    // Keep exactly this release plus the latest previous release for already-open tabs.
    const previous = keys.filter(key => key.startsWith(PREFIX) && key !== CACHE && !key.endsWith('::themes')).slice(-1);
    await Promise.all(keys.filter(key => key.startsWith(PREFIX) && key !== CACHE && key !== PACK_CACHE && !previous.includes(key)&&!previous.some(p=>key===p+'::themes')).map(key => caches.delete(key)));
    await self.clients.claim();
  })());
});

async function releaseNavigation(request) {
  const cache = await caches.open(CACHE);
  const savedIndex = await cache.match(INDEX,{ignoreVary:true});
  try {
    const response = await fetch(request, { cache: 'no-cache' });
    if (response.ok) {
      // A browser can evict the cached shell while retaining its active worker.
      // With no old shell left to run, a healthy network response must remain usable.
      if (!savedIndex) return response;
      const digest = await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer());
      const integrity = 'sha256-' + btoa(String.fromCharCode(...new Uint8Array(digest)));
      // Pin HTML to the same release as cached chunks until the player accepts an update.
      if (integrity === INDEX_INTEGRITY) return response;
    }
  } catch { /* Offline navigation uses this release's complete installed shell. */ }
  return savedIndex || new Response(RECOVERY_HTML, { status: 503, headers: { 'Content-Type': 'text/html; charset=utf-8', 'Cache-Control': 'no-store' } });
}

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Comparison HTML has its own entry point and must never receive the game shell.
    if (url.pathname !== new URL(SCOPE).pathname && url.pathname !== new URL(INDEX).pathname) return;
    event.respondWith(releaseNavigation(request));
    return;
  }
  if (!URLS.has(url.href)) {
    const packed=PACKS.find(asset=>new URL(asset.url,SCOPE).href===url.href);
    if(packed){event.respondWith((async()=>{const cache=await caches.open(PACK_CACHE);const saved=await cache.match(request,{ignoreVary:true});if(saved)return saved;const response=await fetch(new Request(request,{integrity:packed.integrity}));if(response.ok)await cache.put(request,response.clone());return response;})());return;}
    // An older open tab may still request a hashed lazy chunk after clients.claim().
    // Only static JS/CSS under this app's assets directory may use the retained release.
    if (!url.href.startsWith(ASSET_ROOT) || !/\\.(?:js|css)$/.test(url.pathname)) return;
    event.respondWith((async () => {
      const keys = await caches.keys();
      const previous = keys.filter(key => key.startsWith(PREFIX) && key !== CACHE).slice(-1);
      for (const name of previous) {
        const cached = await (await caches.open(name)).match(request,{ignoreVary:true});
        if (cached) return cached;
      }
      return fetch(request);
    })());
    return;
  }
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const cached = await cache.match(request,{ignoreVary:true});
    if (cached) return cached;
    // An evicted entry may only be repaired with exactly the build's recorded content.
    const asset = ASSETS.find(item => new URL(item.url, SCOPE).href === url.href);
    const response = await fetch(request, { integrity: asset.integrity });
    if (response.ok) await cache.put(request, response.clone());
    return response;
  })());
});
`;
}

export async function buildServiceWorker(directory = path.resolve('dist')) {
  const assets = await collectAssets(directory);
  try{const rows=JSON.parse(await readFile(path.join(directory,'assets/v3-manifest.json'),'utf8'));for(const asset of assets)asset.stage=rows.find(row=>row.path===asset.url)?.stage;}catch(error){if(error.code!=='ENOENT')throw error;}
  const source = renderServiceWorker(assets);
  await writeFile(path.join(directory, 'sw.js'), source, 'utf8');
  const core=assets.filter(a=>!/^assets\/v3(?:-b)?\//.test(a.url)||(a.stage??3)<=1||/^assets\/v3(?:-b)?\/(?:vegetable-cart|fruit-cart|chopping-board|fruit-press)-l1\.(?:webp|svg)$/.test(a.url));
  return { files: core.length, bytes: core.reduce((sum, asset) => sum + asset.size, 0),totalBytes:assets.reduce((s,a)=>s+a.size,0),themeFiles:assets.length-core.length };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildServiceWorker(process.argv[2] ? path.resolve(process.argv[2]) : undefined);
  console.log(`PWA: core ${result.files} files ${(result.bytes / 1024 / 1024).toFixed(2)} MiB; ${result.themeFiles} lazy theme assets; complete ${(result.totalBytes/1024/1024).toFixed(2)} MiB.`);
}
