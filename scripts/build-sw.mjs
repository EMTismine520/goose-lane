import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const RUNTIME = readFileSync(new URL('./service-worker-runtime.js', import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const CACHEABLE = /\.(?:html|css|js|mjs|json|webmanifest|webp|png|jpe?g|svg|ico|woff2?|ttf|mp3|ogg|wav)$/i;
export async function collectAssets(directory, prefix = '') {
  const assets = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const relative = prefix + entry.name;
    if (entry.name.startsWith('.')) continue;
    if (entry.isDirectory()) assets.push(...await collectAssets(path.join(directory, entry.name), relative + '/'));
    else if (entry.isFile() && !['sw.js', 'offline-budget.json', 'performance-budget.json'].includes(entry.name) && CACHEABLE.test(entry.name)) {
      const bytes = await readFile(path.join(directory, entry.name));
      assets.push({ url: relative, size: bytes.length, integrity: 'sha256-' + createHash('sha256').update(bytes).digest('base64') });
    }
  }
  return assets.sort((a, b) => a.url.localeCompare(b.url, 'en'));
}
export function renderServiceWorker(assets, coreUrls) {
  const core = assets.filter(asset => coreUrls ? coreUrls.includes(asset.url) : !/^assets\/v3(?:-b)?\//.test(asset.url) || (asset.stage ?? 3) <= 1 || /^assets\/v3(?:-b)?\/(?:vegetable-cart|fruit-cart|chopping-board|fruit-press)-l1\.(?:webp|svg)$/.test(asset.url));
  if (!core.some(asset => asset.url === 'index.html')) throw new Error('PWA build requires dist/index.html. Run vite build first.');
  if (core.reduce((sum, asset) => sum + asset.size, 0) > 5 * 1024 * 1024) throw new Error('PWA precache exceeds 5 MiB.');
  if (assets.reduce((sum, asset) => sum + asset.size, 0) > 16 * 1024 * 1024) throw new Error('Complete offline release exceeds 16 MiB.');
  const version = createHash('sha256').update(JSON.stringify(assets)).update(JSON.stringify(coreUrls ?? null)).update(RUNTIME).digest('hex').slice(0, 20);
  const recovery = '<!doctype html><html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>恢复加载</title></head><body><main><h1>暂时无法加载游戏</h1><p>已保存的进度仍在，请联网后重试。</p><button onclick="location.reload()">重新加载</button><a href="https://emtismine520.github.io/goose-lane-art-preview/recover.html">打开独立试玩</a></main></body></html>';
  return '/* Generated by scripts/build-sw.mjs. */\nconst VERSION = ' + JSON.stringify(version) + ';\nconst ASSETS = ' + JSON.stringify(core) + ';\nconst PACKS = ' + JSON.stringify(assets.filter(asset => !core.includes(asset))) + ';\nconst RECOVERY_HTML = ' + JSON.stringify(recovery) + ';\n' + RUNTIME;
}
export async function gameCoreUrls(directory) {
  let manifest;
  try { manifest = JSON.parse(await readFile(path.join(directory, '.vite/manifest.json'), 'utf8')); }
  catch (error) { if (error.code === 'ENOENT') return undefined; throw error; }
  const urls = new Set(['index.html', 'manifest.webmanifest', 'favicon.svg', 'app-icon-180.png', 'app-icon-192.png', 'app-icon-512.png']);
  const visited = new Set();
  const visit = key => {
    if (visited.has(key)) return; visited.add(key);
    const entry = manifest[key]; if (!entry) throw new Error('Missing game dependency: ' + key);
    urls.add(entry.file); for (const css of entry.css || []) urls.add(css);
    for (const child of [...entry.imports || [], ...entry.dynamicImports || []]) visit(child);
  };
  visit('index.html'); return [...urls];
}
export async function buildServiceWorker(directory = path.resolve('dist')) {
  const assets = await collectAssets(directory);
  for (const [name, variant] of [['v3-manifest.json', 'large'], ['mobile-manifest.json', 'mobile']]) {
    try {
      const rows = JSON.parse(await readFile(path.join(directory, 'assets', name), 'utf8'));
      const byPath = new Map(rows.map(row => [row.path, row]));
      for (const asset of assets) { const row = byPath.get(asset.url); if (row) Object.assign(asset, { role: 'art', variant, stage: row.stage }); }
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  for (const asset of assets) if (/^assets\/(?:items\/|entities\/|foods\.webp$|street\.webp$)/.test(asset.url) && !asset.role) Object.assign(asset, { role: 'legacy', stage: 1 });
  const coreUrls = await gameCoreUrls(directory);
  const source = renderServiceWorker(assets, coreUrls);
  await writeFile(path.join(directory, 'sw.js'), source, 'utf8');
  const core = JSON.parse(source.match(/const ASSETS = (.*);/)[1]);
  const result = { files: core.length, bytes: core.reduce((sum, asset) => sum + asset.size, 0), totalBytes: assets.reduce((sum, asset) => sum + asset.size, 0), themeFiles: assets.length - core.length, coreUrls: core.map(asset => asset.url) };
  await writeFile(path.join(directory, 'offline-budget.json'), JSON.stringify(result, null, 2) + '\n');
  return result;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildServiceWorker(process.argv[2] ? path.resolve(process.argv[2]) : undefined);
  console.log('PWA: core ' + result.files + ' files ' + (result.bytes / 1024 / 1024).toFixed(2) + ' MiB; ' + result.themeFiles + ' on-demand resources; complete ' + (result.totalBytes / 1024 / 1024).toFixed(2) + ' MiB.');
}
